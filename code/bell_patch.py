import math, ramanujan_upper as r
ROWS=[(3e12,29,0.9927,37341.72,14.160),(29,30,.9927,37564.18,14.084),(30,31,.9925,40014.59,13.588),(31,32,.9923,42840.01,13.108),(32,33,.9921,46015.02,12.647),(33,34,.9919,49270.71,12.226),(34,35,.9918,52249.66,11.856),(35,36,.9916,55524.80,11.505),(36,37,.9914,59715.72,11.134),(37,38,.9912,64228.93,10.782),(38,39,.9910,68446.65,10.475),(39,40,.9909,71907.32,10.217),(40,41,.9907,76267.80,9.951)]
base=r.logN_density
def logN(s,T,bell_scale=1.0):
    v=base(s,T,bell_scale); lT=math.log(T)
    for i,(a,b,al,C,B) in enumerate(ROWS):
        lo=math.log(a) if i==0 else a
        if lo<lT<=b and s>=al:
            v=min(v, math.log(C*bell_scale)+B*(1-s)*lT)
    return v
r.logN_density=logN
